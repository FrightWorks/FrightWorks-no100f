#!/usr/bin/env bash
# Native Linux (x86_64) build of FrightWorks: portable tools -> translate -> configure -> compile -> stage Play/.
# The Linux counterpart of tools/build-no100f.ps1. Needs clang, ninja, python3 (Pillow), ImageMagick, curl and bsdtar
# (or 7z / unrar) on PATH; CMake and the .NET 10 SDK are downloaded into toolchain/ (nothing system-wide).
#   tools/build-no100f-linux.sh [path/to/game.iso]
# FRIGHTWORKS_JOBS=<n> limits the parallel jobs (default: all cores).
# The disc image is only needed the first time (it is extracted to Disc/DATA). The game ends up in "Play/FrightWorks Game",
# with settings, saves and logs in Play/UserData (Play/portable.txt is the marker).
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
wc="$root/wiicompiled"
toolchain="$root/toolchain"
logs="$root/build-logs"
build="$wc/native-build-linux"
play="$root/Play"
jobs="${FRIGHTWORKS_JOBS:-$(nproc)}"  # FRIGHTWORKS_JOBS caps the parallel jobs (the translator and the compiler)
mkdir -p "$logs"

status() { printf '%s %s\n' "$(date +%T)" "$*" | tee -a "$logs/status-linux.txt"; }
step() {  # step <name> <command...>: runs it with output in build-logs/<name>.log, stops on failure
    local name="$1"; shift
    status "$name: started"
    if ! "$@" >"$logs/$name.log" 2>&1; then
        status "$name: FAILED, see $logs/$name.log"
        tail -n 40 "$logs/$name.log"
        exit 1
    fi
    status "$name: ok"
}

# 0. The disc: Disc/DATA (sys/ + files/) and game/main.dol, the translation input.
if [[ ! -f "$root/Disc/DATA/sys/boot.bin" ]]; then
    [[ $# -ge 1 ]] || { echo "First build: pass your GIHE78 rev 1 disc image (.iso/.gcm)." >&2; exit 1; }
    step extract python3 "$root/tools/gc_extract.py" "$1" "$root/Disc/DATA"
fi
mkdir -p "$root/game"
[[ -f "$root/game/main.dol" ]] || cp "$root/Disc/DATA/sys/main.dol" "$root/game/main.dol"

# 1. Portable CMake and .NET 10 SDK
if [[ ! -x "$toolchain/CMake/bin/cmake" ]]; then
    status 'tools: downloading CMake 4.3.3'
    mkdir -p "$toolchain"
    curl -fsSL https://github.com/Kitware/CMake/releases/download/v4.3.3/cmake-4.3.3-linux-x86_64.tar.gz |
        tar -xz -C "$toolchain"
    mv "$toolchain/cmake-4.3.3-linux-x86_64" "$toolchain/CMake"
fi
# The .NET 10 SDK: tools/get-dotnet.py (also what tools/get-dotnet.ps1 runs on Windows) installs it into toolchain/dotnet,
# beside an older SDK if there is one, and prints the path of dotnet as its last line.
step get-dotnet python3 "$root/tools/get-dotnet.py"
cmake="$toolchain/CMake/bin/cmake"
dotnet="$(tail -n 1 "$logs/get-dotnet.log")"
export DOTNET_ROLL_FORWARD=Major DOTNET_CLI_TELEMETRY_OPTOUT=1

# 2. Translate
cd "$wc"
project=projects/no100f/recomp.yml
translator=translator/src/Translator.Cli/bin/Release/net10.0/Translator.Cli.dll
[[ -f "$translator" ]] || step translator-build "$dotnet" build translator/src/Translator.Cli -c Release
sha="$(sha256sum "$root/game/main.dol" | cut -d' ' -f1)"
sha_inc=runtime/src/hle/scooby_dol_sha256.inc
sha_text="// AUTO-GENERATED by tools/build-no100f.ps1: SHA-256 of the game/main.dol the translation was built from.
constexpr char kDolSha256[] = \"$sha\";"
[[ "$(tr -d '\r' <"$sha_inc" 2>/dev/null)" == "$sha_text" ]] || printf '%s\n' "$sha_text" >"$sha_inc"
step translate "$dotnet" "$translator" translate-recursive 0x80016A00 --project "$project" \
    --outdir generated/functions --output-metadata generated/base_translation_output.json \
    --production-source-bundle generated/base_translation_sources.bin \
    --no-function-files --prune-stale --threads "$jobs"
step data-init "$dotnet" "$translator" generate-data-init --project "$project"
step shards "$dotnet" "$translator" emit-build-shards --project "$project" \
    --base-metadata generated/base_translation_output.json --base-functions-dir generated/functions \
    --native-source-dir runtime/src --out generated/build_shards

# 3. Configure and compile (pinned dependencies, including the Linux Dawn package, are fetched by CMake)
step configure-linux "$cmake" -S runtime -B "$build" -G Ninja \
    -DCMAKE_C_COMPILER=clang -DCMAKE_CXX_COMPILER=clang++ \
    -DCMAKE_BUILD_TYPE=Release -DCMAKE_SYSTEM_PROCESSOR=x86_64 \
    -DAURORA_DAWN_PROVIDER=package -DAURORA_SDL3_PROVIDER=vendor -DCMAKE_POLICY_DEFAULT_CMP0168=NEW \
    -DRECOMP_TRANSLATED_COMPILE_JOBS="$jobs" -DRECOMP_GIT_EXECUTABLE="$(command -v git || true)"
step compile-linux "$cmake" --build "$build" --target WiiCompiled --parallel "$jobs"

# 4. Stage Play/: the program, its runtime files and a Config.toml pointing at Disc/DATA
pkill -f "^$play/FrightWorks Game" 2>/dev/null || true
install -m 755 "$build/WiiCompiled" "$play/FrightWorks Game"
cp "$build/dsp_coef.bin" "$build/cacert.pem" "$build/initial_pipeline_cache.db" "$play/"
mkdir -p "$play/UserData"
[[ -f "$play/UserData/Config.toml" ]] || printf "[paths]\ndvd_root = '../../Disc/DATA'\n" >"$play/UserData/Config.toml"
status "copied to $play/FrightWorks Game"

# 5. HD texture pack (downloaded once into texture_pack/ScoobyHD), its fixes (tools/hd-pack-fixes.py, from the disc's own
# textures in Disc/DATA) and the button prompt icons: tools/stage-assets.py, the same script the Windows build runs, so a
# fix to the pack reaches Linux builds too.
step stage-assets python3 "$root/tools/stage-assets.py" --game-dir "$play"
grep -E '^(HD pack|Button icons|WARNING)' "$logs/stage-assets.log" | while IFS= read -r line; do status "$line"; done || true
status "DONE: run $play/FrightWorks Game (or the launcher: tools/build-launcher.sh)"
